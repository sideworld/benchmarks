#!/usr/bin/env bash
# Write Mastodon's .env.production -- the one file its compose needs and does not ship.
# Secrets are minted with Mastodon's own tasks in a throwaway container of its own image;
# nothing is invented. Idempotent: an existing file is kept (its secrets encrypt the DB).
#   benchmarks/mastodon/init-env.sh [local_domain]
set -euo pipefail
MD=${MD_DIR:-/tank/work/mastodon}; IMG=${MD_IMAGE:-ghcr.io/mastodon/mastodon:v4.7.2}
DOMAIN=${1:-${LOCAL_DOMAIN:-mastodon.test}}
OUT=$MD/.env.production
if [ -s "$OUT" ]; then echo "$OUT exists; keeping it"; exit 0; fi
mint() { docker run --rm -e RAILS_ENV=production -e SECRET_KEY_BASE=x -e OTP_SECRET=x "$IMG" "$@"; }
SECRET_KEY_BASE=$(mint bin/rails secret); OTP_SECRET=$(mint bin/rails secret)
VAPID=$(mint bin/rails mastodon:webpush:generate_vapid_key)
ENC=$(mint bin/rails db:encryption:init | grep -E '^ACTIVE_RECORD_ENCRYPTION_')
cat > "$OUT" <<ENV
# Generated by benchmarks/mastodon/init-env.sh -- not committed (secrets).
LOCAL_DOMAIN=$DOMAIN
SINGLE_USER_MODE=false
BIND=0.0.0.0
RAILS_LOG_LEVEL=warn
DEFAULT_LOCALE=en
# databases (compose service names; postgres is trust-auth per Mastodon's compose)
DB_HOST=db
DB_PORT=5432
DB_USER=postgres
DB_NAME=mastodon_production
DB_PASS=
REDIS_HOST=redis
REDIS_PORT=6379
ES_ENABLED=false
# storage: local files under public/system (S3 off)
S3_ENABLED=false
# email -> Mailpit in the compose
SMTP_SERVER=mailpit
SMTP_PORT=1025
SMTP_AUTH_METHOD=none
SMTP_OPENSSL_VERIFY_MODE=none
SMTP_FROM_ADDRESS=notifications@$DOMAIN
# secrets minted by Mastodon's own tasks
SECRET_KEY_BASE=$SECRET_KEY_BASE
OTP_SECRET=$OTP_SECRET
$VAPID
$ENC
ENV
chmod 600 "$OUT"; echo "wrote $OUT ($(wc -l < "$OUT") lines) for LOCAL_DOMAIN=$DOMAIN"
