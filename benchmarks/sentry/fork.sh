#!/usr/bin/env bash
# Compose fork of the Sentry baseline on ZFS clones.
#   benchmarks/sentry/fork.sh up <k>   |   benchmarks/sentry/fork.sh down <k>
# Fork k serves on 127.0.0.1:9<k>00 and owns tank/se-f<k>-*. Nothing outside those names is touched.
set -euo pipefail
ACT=${1:?up|down}; K=${2:?k}
APP=${SENTRY_DIR:-/tank/work/sentry-self-hosted}
PROJ=se-f$K
BIND=${BIND:-9${K}00}
SETS="pg ch kafka redis seaweedfs"
OVR=$APP/docker-compose.fork$K.yml
# SENTRY_BIND is exported into compose rather than overridden in the fork file: compose merges a
# `ports:` list by APPENDING, so an override that adds "9100:80" leaves the inherited "9000:80"
# in place, the fork's nginx tries to publish a port the baseline already owns, and it stays in
# `Created` forever. Interpolating the one variable the upstream file already uses avoids that.
dc() { env SENTRY_BIND="$BIND" docker compose -p "$PROJ" --project-directory "$APP" --env-file "$APP/.env" -f "$APP/docker-compose.yml" -f "$OVR" "$@"; }

if [ "$ACT" = down ]; then
  dc down -v --remove-orphans >/dev/null 2>&1 || true
  for s in $SETS; do zfs list -H -o name "tank/se-f$K-$s" >/dev/null 2>&1 && zfs destroy -r "tank/se-f$K-$s"; done
  rm -f "$OVR"; echo "fork $K down; datasets removed"; exit 0
fi

t0=$(date +%s.%N)
for s in $SETS; do
  zfs list -H -o name "tank/se-f$K-$s" >/dev/null 2>&1 || zfs clone "tank/se-$s@se-base" "tank/se-f$K-$s"
done
t1=$(date +%s.%N)
cat > "$OVR" <<YAML
# generated by benchmarks/sentry/fork.sh -- fork $K on ZFS clones of @se-base
services:
  postgres:   {volumes: [/tank/se-f$K-pg:/var/lib/postgresql/data]}
  clickhouse:
    volumes:
      - /tank/se-f$K-ch:/var/lib/clickhouse
      - ./clickhouse/config.xml:/etc/clickhouse-server/config.d/sentry.xml:ro
      - ./clickhouse/default-password.xml:/etc/clickhouse-server/users.d/default-password.xml:ro
  kafka:      {volumes: [/tank/se-f$K-kafka:/var/lib/kafka/data]}
  redis:
    volumes:
      - /tank/se-f$K-redis:/data
      - ./redis.conf:/usr/local/etc/redis/redis.conf:ro
  seaweedfs:  {volumes: [/tank/se-f$K-seaweedfs:/data]}
YAML
dc up -d --wait >/dev/null 2>&1 || true
t2=$(date +%s.%N)
until [ "$(curl -sS -o /dev/null -m 3 -w '%{http_code}' "http://127.0.0.1:$BIND/_health/" 2>/dev/null)" = 200 ]; do sleep 1; done
t3=$(date +%s.%N)
echo "$t0 $t1 $t2 $t3" | awk '{printf "fork '"$K"': clone %.2fs  up %.1fs  /_health/ 200 at %.1fs  -> http://127.0.0.1:'"$BIND"'/\n", $2-$1, $3-$2, $4-$1}'
