#!/usr/bin/env bash
# The alternative baseline: what a team does today without the fork runtime. A database
# "branch" (a ZFS clone of tank/md-pg@md-base stands in for a Neon branch), a conventional
# cold deploy of the changed web app against it -- fresh containers, EMPTY Redis, fresh Sidekiq,
# empty media -- on offset ports. Measures: time to serve /api/v1/instance; time until the
# heavy-follow account's home timeline is served with warm caches (Mastodon rebuilds the feed on
# demand: 206 while regenerating, 200 when done). Then lists what this path cannot reach.
#   benchmarks/mastodon/alt-baseline.sh up|down    (env: IMAGE=<changed web image>, default v4.7.2)
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd); MD=${MD_DIR:-/tank/work/mastodon}
P=md-alt; OFF=13000; IMAGE=${IMAGE:-ghcr.io/mastodon/mastodon:v4.7.2}
OV=$HERE/compose/docker-compose.$P.yml
H=(-H "X-Forwarded-Proto: https" -H "Host: mastodon.test")
dc() { docker compose -p $P --project-directory "$MD" -f "$MD/docker-compose.yml" -f "$HERE/compose/docker-compose.md.yml" -f "$OV" "$@"; }
case "${1:-up}" in
up)
  zfs list -H -o name tank/md-altpg >/dev/null 2>&1 || zfs clone -o mountpoint=/tank/md-altpg tank/md-pg@md-base tank/md-altpg
  for d in md-altredis md-altsystem; do zfs list -H -o name tank/$d >/dev/null 2>&1 || zfs create -o compression=lz4 -o mountpoint=/tank/$d tank/$d; done
  chown 999:999 /tank/md-altredis; chown 991:991 /tank/md-altsystem
  cat > "$OV" <<YML
# generated by alt-baseline.sh: DB branch + fresh everything else, ports +$OFF, changed web image
services:
  db:        { volumes: !override ['/tank/md-altpg:/var/lib/postgresql/data'] }
  redis:     { volumes: !override ['/tank/md-altredis:/data'] }
  web:       { image: $IMAGE, ports: !override ['127.0.0.1:$((3000+OFF)):3000'], volumes: !override ['/tank/md-altsystem:/mastodon/public/system'] }
  sidekiq:   { image: $IMAGE, volumes: !override ['/tank/md-altsystem:/mastodon/public/system'] }
  streaming: { ports: !override ['127.0.0.1:$((4000+OFF)):4000'] }
  mailpit:   { ports: !override ['127.0.0.1:$((8025+OFF)):8025'] }
networks: { external_network: { name: ${P}_external }, internal_network: { name: ${P}_internal, internal: true } }
YML
  echo "== alt baseline: DB clone + empty redis + fresh containers ($IMAGE), web on $((3000+OFF))"
  t0=$(date +%s.%N)
  dc up -d --wait 2>&1 | grep -iE 'unhealthy|error' || true
  for i in $(seq 1 600); do c=$(curl -s -m 5 -o /dev/null -w '%{http_code}' "${H[@]}" "http://127.0.0.1:$((3000+OFF))/api/v1/instance"); [ "$c" = 200 ] && break; sleep 0.5; done
  t1=$(date +%s.%N); echo "t_alt_instance_200=$(echo "$t0 $t1" | awk '{printf "%.1f", $2-$1}')s (http $c)"
  TOK=$(MD_PROJECT=$P "$HERE/make-token.sh" heavyfollower)
  "$HERE/regen-feed.sh" heavyfollower $P >/dev/null     # what the first sign-in would do; an API read alone serves 200 []
  code=; n=0
  for i in $(seq 1 1200); do
    out=$(curl -s -m 60 -w ' %{http_code}' "${H[@]}" -H "Authorization: Bearer $TOK" "http://127.0.0.1:$((3000+OFF))/api/v1/timelines/home?limit=20")
    code=${out##* }; body=${out% *}; n=$(echo "$body" | python3 -c 'import sys,json
try: print(len(json.load(sys.stdin)))
except Exception: print(0)')
    [ "$code" = 200 ] && [ "$n" -gt 0 ] && break; sleep 1
  done
  t2=$(date +%s.%N); echo "t_alt_home_timeline_warm=$(echo "$t0 $t2" | awk '{printf "%.1f", $2-$1}')s (http $code, $n statuses; feed regenerated on demand by RegenerationWorker)"
  echo "redis keys after: $(docker exec $P-redis-1 redis-cli DBSIZE)   sidekiq processed: $(MD_PROJECT=$P "$HERE/md.sh" exec -T web bin/rails runner 'require "sidekiq/api"; puts Sidekiq::Stats.new.processed' 2>/dev/null | tail -1)"
  ;;
down)
  dc down --remove-orphans 2>&1 | tail -1 || true
  for d in md-altpg md-altredis md-altsystem; do zfs list -H -o name tank/$d >/dev/null 2>&1 && zfs destroy tank/$d; done
  rm -f "$OV"; echo "alt baseline removed" ;;
esac
