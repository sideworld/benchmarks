#!/usr/bin/env bash
# The alternative a team would actually reach for today, measured on the same box, on the same
# data, with the same changed image: a ZFS clone of the database as a "database branch", plus a
# conventional cold `docker compose up` of the changed server against it.
#
#   benchmarks/mattermost/alt-baseline.sh up <k> | down <k>
#
# It owns tank/mm-alt<k>-* and the compose project mm-alt<k>, and nothing else. Reports:
#   t_clone      making the branch
#   t_api        cold up --wait -> /api/v4/system/ping answers 200
#   t_history_1  first channel-history page of the busiest channel (cold caches)
#   t_history_w  the same page warm
set -euo pipefail
ACT=${1:?up|down}; K=${2:-1}
SPEC_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
PROJ=mm-alt$K
# Host ports are shared with three other worlds on this box; 5441 was already held by the
# specimen's gateway database and Docker reports that only as "port is already allocated".
PORT=$((8080 + K)); PGP=$((5454 + K)); MIP=$((9130 + K)); IBP=$((9030 + K))
SNAP=${MM_SNAP:-mm-base}
OVR=$SPEC_DIR/compose/docker-compose.alt$K.yml
el() { echo "$1 $(date +%s.%N)" | awk '{printf "%.1f", $2-$1}'; }
dc() { docker compose -p "$PROJ" --project-directory /tank/work/mattermost \
        --env-file "$SPEC_DIR/compose/mm.env" -f "$SPEC_DIR/compose/docker-compose.mm.yml" -f "$OVR" "$@"; }

if [ "$ACT" = down ]; then
  dc down -v --remove-orphans >/dev/null 2>&1 || true
  for d in tank/mm-alt$K-pg tank/mm-alt$K-minio; do
    zfs list -H -o name "$d" >/dev/null 2>&1 || continue
    o=$(zfs get -H -o value origin "$d")
    case "$o" in tank/mm-pg@*|tank/mm-minio@*) zfs destroy "$d" && echo "  destroyed $d (origin $o)" ;;
      *) echo "  refusing to destroy $d: origin '$o' is not a clone of the Mattermost baseline" >&2; exit 1 ;; esac
  done
  rm -f "$OVR"; exit 0
fi

zfs list -H -o name "tank/mm-pg@$SNAP" >/dev/null 2>&1 || { echo "no snapshot tank/mm-pg@$SNAP" >&2; exit 1; }
echo "== the database branch"
t0=$(date +%s.%N)
zfs clone -o mountpoint=/tank/mm-alt$K-pg    "tank/mm-pg@$SNAP"    "tank/mm-alt$K-pg"
zfs clone -o mountpoint=/tank/mm-alt$K-minio "tank/mm-minio@$SNAP" "tank/mm-alt$K-minio"
T_CLONE=$(el "$t0"); echo "  t_clone=${T_CLONE}s   (copy-on-write; the branch costs no space until it is written to)"

cat > "$OVR" <<EOF
# Generated by alt-baseline.sh -- the conventional alternative, for comparison only.
services:
  postgres:
    container_name: ${PROJ}-postgres
    volumes: ["/tank/mm-alt$K-pg:/var/lib/postgresql/data"]
    ports: !override ["127.0.0.1:$PGP:5432"]
  minio:
    container_name: ${PROJ}-minio
    volumes: ["/tank/mm-alt$K-minio:/data"]
    ports: !override ["127.0.0.1:$MIP:9000"]
  inbucket:
    container_name: ${PROJ}-inbucket
    ports: !override ["127.0.0.1:$IBP:9001"]
  mattermost:
    container_name: ${PROJ}-server
    # the CHANGED server, the same image the Firecracker fork was given, so the two paths are
    # being compared on the same work rather than on different work
    image: "${ALT_IMAGE:-sideworld/mattermost-server:v11.11.0-pr}"
    ports: !override ["127.0.0.1:$PORT:8065"]
EOF

echo "== conventional cold deploy of the changed server against the branch"
t0=$(date +%s.%N)
up_rc=0; dc up -d --wait > "$SPEC_DIR/.alt$K.log" 2>&1 || up_rc=$?
if [ "$up_rc" != 0 ]; then
  # A container stuck in `Created` means the up failed; without this the loop below spends ten
  # minutes politely waiting for a server that was never started, and reports t_api=604s.
  bad=$(docker ps -a --filter "name=$PROJ" --format '{{.Names}} {{.Status}}' | grep -v ' Up ' || true)
  echo "  up --wait exited $up_rc" >&2
  [ -n "$bad" ] && { echo "$bad" | sed 's/^/    /' >&2; docker inspect $(echo "$bad" | head -1 | awk '{print $1}') --format '    {{.State.Error}}' >&2; }
  exit 1
fi
for _ in $(seq 1 600); do
  [ "$(curl -sS -o /dev/null -m 5 -w '%{http_code}' "http://127.0.0.1:$PORT/api/v4/system/ping" 2>/dev/null)" = 200 ] && break
  sleep 1
done
T_API=$(el "$t0"); echo "  t_api=${T_API}s   (cold up --wait -> /api/v4/system/ping 200)"

TOK=$(cat "$SPEC_DIR/.token"); TEAM=$(cat "$SPEC_DIR/.core-team")
H=(-H "Authorization: Bearer $TOK" -H 'Content-Type: application/json')
CH=$(curl -sS -m 120 "${H[@]}" "http://127.0.0.1:$PORT/api/v4/teams/$TEAM/channels/name/gen-1" \
     | python3 -c "import json,sys;print(json.load(sys.stdin).get('id',''))")
# Count the posts, do not discard the body: a 403 also returns instantly, and "0.0 s" for a
# channel-history page is what a failure looks like, not what a fast page looks like.
page() { curl -sS -m 300 "${H[@]}" "http://127.0.0.1:$PORT/api/v4/channels/$CH/posts?per_page=60" \
         | python3 -c "import json,sys
try: print(len(json.load(sys.stdin).get('posts',{})))
except Exception: print(0)"; }
ms() { echo "$1 $(date +%s.%N)" | awk '{printf "%.0f", ($2-$1)*1000}'; }
t0=$(date +%s.%N); N1=$(page); T_H1=$(ms "$t0")
t0=$(date +%s.%N); NW=$(page); T_HW=$(ms "$t0")
[ "${N1:-0}" -ge 55 ] || { echo "  channel history returned $N1 posts, not a page" >&2; exit 1; }
echo "  t_history_1=${T_H1} ms ($N1 posts, cold caches)   t_history_w=${T_HW} ms ($NW posts, warm)"
echo "  marker: SideworldPR=$(curl -sS -m 10 "http://127.0.0.1:$PORT/api/v4/system/ping" | python3 -c "
import json,sys
try: print(json.load(sys.stdin).get('SideworldPR','<absent>'))
except Exception: print('<no json>')")"
echo
echo "alt-baseline $PROJ: clone ${T_CLONE}s, api ${T_API}s, history cold ${T_H1} ms / warm ${T_HW} ms, on port $PORT"
